import {
  normalizeFoundation,
  beginBusinessProfile,
  saveCampaignDraft,
  submitCampaignDraft,
  saveBrandProfile,
  createStudioSet,
  creativeMatchesBrand,
  recordTrackingEvent,
  updateTracking,
} from "./foundation-model.mjs";
import {
  campaignDialog,
  brandDialog,
  studioDialog,
  studioAssetDialog,
  eventDialog,
  confirmationDialog,
} from "./foundation-views.mjs";
import { assert, log } from "./model.mjs";

const formIds = new Set([
  "f-business-form",
  "f-brand-form",
  "f-campaign-goal-form",
  "f-campaign-draft-form",
  "f-confirm-campaign-form",
  "f-studio-form",
  "f-event-form",
]);

/** Browser-fixture controls for the documented Hellyeah customer workflow. */
export function createFoundationController({
  win,
  ui,
  getState,
  mutate,
  navigate,
  openDialog,
  closeDialog,
  notify,
}) {
  ui.foundationDrafts ??= {};
  const state = () => normalizeFoundation(getState());
  const fields = (form) => Object.fromEntries(new win.FormData(form));
  const showCampaign = (id) => openDialog(campaignDialog(state(), id));

  function remember(el) {
    const form = el.form;
    if (!formIds.has(form?.id)) return false;
    ui.foundationDrafts[form.id] = fields(form);
    return true;
  }

  function saveVisibleDraft(id) {
    const form = win.document.getElementById("f-campaign-draft-form");
    if (!form || (form.dataset.id && form.dataset.id !== id)) return;
    assert(form.reportValidity(), "Complete the campaign fields before continuing.");
    mutate((s) => saveCampaignDraft(s, fields(form), id));
    delete ui.foundationDrafts[form.id];
  }

  const actions = {
    "f-new-campaign": () => {
      delete ui.foundationDrafts["f-campaign-goal-form"];
      navigate("new-campaign");
    },
    "f-goal-example": (el) => {
      const input = win.document.querySelector('#f-campaign-goal-form [name="goalSentence"]');
      if (!input) return;
      input.value = el.dataset.goal || "";
      remember(input);
      input.focus();
    },
    "f-use-studio": (el) => {
      ui.foundationAssetId = el.dataset.id;
      navigate("new-campaign");
    },
    "f-finish-studio": (el) => {
      mutate((s) => {
        const asset = s.assets.find((a) => a.id === el.dataset.id);
        assert(asset, "Creative Set not found.");
        if (asset.status === "Ready" && asset.textReady && asset.landscape && asset.square) return;
        asset.status = "Ready";
        asset.textReady = true;
        asset.landscape = true;
        asset.square = true;
        asset.version += 1;
        asset.source = "Studio sample";
        log(s, `Completed sample previews for “${asset.name}”. No images were generated by a live service.`, "creative");
      });
      openDialog(studioAssetDialog(state(), el.dataset.id));
      notify("Sample creative previews are ready.");
    },
    "f-campaign": (el) => showCampaign(el.dataset.id),
    "f-edit-brand": () => openDialog(brandDialog(state())),
    "f-studio-create": () => openDialog(studioDialog(state())),
    "f-studio-asset": (el) => openDialog(studioAssetDialog(state(), el.dataset.id)),
    "f-tracking-method": (el) => {
      mutate((s) => updateTracking(s, el.dataset.method));
      notify("Demo installation selected. Record a sample event to verify the connection.");
    },
    "f-track-event": () => openDialog(eventDialog(state())),
    "f-submit-campaign": (el) => {
      saveVisibleDraft(el.dataset.id);
      openDialog(confirmationDialog(state(), el.dataset.id));
    },
    "f-review-demo": (el) => {
      mutate((s) => {
        const campaign = s.campaigns.find((c) => c.id === el.dataset.id);
        assert(campaign?.status === "In Review", "This campaign is not awaiting review.");
        campaign.status = "Serving";
        campaign.demoReviewedAt = new Date().toISOString();
        log(s, `Demo review approved for “${campaign.name}”. No live ad was created.`, "campaign");
      });
      showCampaign(el.dataset.id);
      notify("Demo campaign is now serving. No real ads were launched.");
    },
    "f-onboard-next": () => {
      if (ui.route === "onboarding") {
        navigate("brand");
      } else {
        ui.foundationOnboarding = false;
        navigate("new-campaign");
      }
    },
  };

  function submit(form) {
    if (!formIds.has(form.id)) return false;
    assert(form.reportValidity(), "Complete the required fields.");
    const data = fields(form);
    if (form.id === "f-business-form") {
      let website = String(data.website ?? data.businessWebsite ?? "").trim();
      if (!website.includes("://") && website.includes("@")) website = website.split("@").at(-1);
      if (!website.includes("://")) website = `https://${website}`;
      let url;
      try { url = new URL(website); } catch { throw new Error("Enter a business website or work email."); }
      assert(url.hostname.includes(".") && url.protocol === "https:", "Enter a valid HTTPS business website.");
      assert(!["gmail.com", "yahoo.com", "outlook.com", "hotmail.com", "icloud.com"].includes(url.hostname), "Enter your business website instead of a personal email provider.");
      const name = String(data.name ?? "").trim() || url.hostname.replace(/^www\./, "");
      const current = state().brand;
      const sameBusiness = new URL(current.website).hostname === url.hostname && current.name === name;
      if (!sameBusiness) mutate((s) => beginBusinessProfile(s, { name, website: url.origin }));
      ui.foundationOnboarding = true;
      navigate("brand");
      notify("Business saved. Review your profile; this demo does not research the website.");
    }
    if (form.id === "f-brand-form") {
      mutate((s) => saveBrandProfile(s, data));
      closeDialog();
      notify("Brand Profile saved. New work will use this version.");
    }
    if (form.id === "f-campaign-goal-form") {
      const s = state();
      const goalSentence = String(data.goalSentence ?? data.prompt ?? "").trim();
      assert(goalSentence.length >= 10, "Describe the result, audience, and market in one sentence.");
      ui.foundationDrafts[form.id] = data;
      if (!s.brand.complete) {
        ui.foundationOnboarding = true;
        navigate("brand");
        notify("Complete your Brand Profile before preparing the campaign.");
        return true;
      }
      const selectedId = data.creativeId || ui.foundationAssetId;
      const creative = selectedId
        ? s.assets.find(asset => asset.id === selectedId)
        : s.assets.find(asset => asset.textReady && creativeMatchesBrand(s, asset));
      if (!creative?.textReady || !creativeMatchesBrand(s, creative)) {
        openDialog(studioDialog(s));
        notify("Create a sample Creative Set for this business, then use it in your campaign. Your goal is saved.");
        return true;
      }
      const campaign = mutate((draft) => saveCampaignDraft(draft, {
        name: data.name?.trim() || goalSentence.slice(0, 80),
        goalSentence,
        channel: data.channel || "Search",
        goal: data.goal || "conversions",
        destination: data.destination || s.brand.website,
        dailyBudget: data.dailyBudget || 50,
        days: data.days || 14,
        market: data.market || s.brand.market || "United States",
        language: data.language || "English",
        creativeId: creative.id,
      }));
      showCampaign(campaign.id);
      notify("Draft prepared from demo defaults. Review the creative, audience, and budget.");
    }
    if (form.id === "f-campaign-draft-form") {
      const campaign = mutate((s) => saveCampaignDraft(s, data, form.dataset.id));
      showCampaign(campaign.id);
      notify("Campaign draft saved. No funds have been reserved.");
    }
    if (form.id === "f-confirm-campaign-form") {
      const campaign = mutate((s) => submitCampaignDraft(s, form.dataset.id, data.confirmed === "on"));
      showCampaign(campaign.id);
      notify("Campaign submitted for demo review. Its maximum budget was reserved once.");
    }
    if (form.id === "f-studio-form") {
      const asset = mutate((s) => createStudioSet(s, data));
      openDialog(studioAssetDialog(state(), asset.id));
      notify("Sample Creative Set saved with copy, landscape, and square previews.");
    }
    if (form.id === "f-event-form") {
      mutate((s) => recordTrackingEvent(s, { ...data, conversion: data.conversion === "on", value: Number(data.value || 0) }));
      closeDialog();
      notify("Sample X-Ray event recorded. Conversion readiness has been updated.");
    }
    delete ui.foundationDrafts[form.id];
    return true;
  }

  return { actions, submit, input: remember, change: remember };
}
